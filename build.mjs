import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = dirname(fileURLToPath(import.meta.url));
process.chdir(root);
const css = await readFile('src/styles.css', 'utf8');
const result = await build({
  absWorkingDir: root, entryPoints: ['src/client.ts'], bundle: true, write: false,
  format: 'cjs', platform: 'browser', target: 'es2022', minify: true,
  define: { __PLUGIN_CSS__: JSON.stringify(css) },
});
await mkdir('lib', { recursive: true });
const bundle = '/* Generated by build.mjs; edit src/client.ts and src/styles.css. */\n'
  + 'window.__ModuleLoader__.load({id:"dsh-theme-endfield-style",factory:function(require){var module={exports:{}};var exports=module.exports;\n'
  + result.outputFiles[0].text + '\nreturn module.exports;}});\n';
await writeFile(resolve(root, 'lib', 'client.js'), bundle);
console.log('Built lib/client.js (' + bundle.length + ' bytes)');
